/**
 * Переменные среды, которые читает код OneScript проекта.
 * Запуск: npm run test:node
 */
import { describe, test } from 'node:test';
import assert from 'node:assert/strict';
import { environmentVariablesInCode, type SourceFile } from '../../shared/codeEnvironmentVariables';

const script = (...lines: string[]): SourceFile => ({ text: lines.join('\n') });
const module = (moduleName: string, ...lines: string[]): SourceFile => ({ moduleName, text: lines.join('\n') });

describe('environmentVariablesInCode', () => {
	test('строковый литерал встроенной функции на обоих языках', () => {
		assert.deepEqual(
			environmentVariablesInCode([
				script(
					'Токен = ПолучитьПеременнуюСреды("GITHUB_TOKEN");',
					'Если GetEnvironmentVariable("CI") = "true" Тогда',
					'КонецЕсли;'
				),
			]),
			['CI', 'GITHUB_TOKEN']
		);
	});

	test('комментарии, строки и имена из выражений не дают переменных', () => {
		assert.deepEqual(
			environmentVariablesInCode([
				script(
					'// ПолучитьПеременнуюСреды("COMMENTED")',
					'Сообщить("ПолучитьПеременнуюСреды(""IN_STRING"")");',
					'Префикс = ПолучитьПеременнуюСреды("PREFIX_" + Имя);',
					'Значение = ПолучитьПеременнуюСреды(Имя);',
					'Текст = "первая строка',
					'|ПолучитьПеременнуюСреды(""MULTILINE"")";',
					'Хвост = ПолучитьПеременнуюСреды("AFTER_MULTILINE");'
				),
			]),
			['AFTER_MULTILINE']
		);
	});

	test('обёртка в модуле: вызов через имя модуля и внутри модуля', () => {
		assert.deepEqual(
			environmentVariablesInCode([
				module(
					'ТестовыеУтилиты',
					'Функция ПолучитьПеременнуюСредыИлиЗначение(ИмяПеременной, ЗначениеПоУмолчанию) Экспорт',
					'	ПеременнаяСреды = ПолучитьПеременнуюСреды(ИмяПеременной);',
					'	Если ПеременнаяСреды = Неопределено Тогда',
					'		ПеременнаяСреды = ЗначениеПоУмолчанию;',
					'	КонецЕсли;',
					'	Возврат ПеременнаяСреды;',
					'КонецФункции',
					'Функция ИсточникСТранзакциями() Экспорт',
					'	Возврат ПолучитьПеременнуюСредыИлиЗначение("RUN_INTEGRATION", "true");',
					'КонецФункции'
				),
				script(
					'#Использовать "utils"',
					'Хост = ТестовыеУтилиты.ПолучитьПеременнуюСредыИлиЗначение("DB_HOST", "localhost");'
				),
			]),
			['DB_HOST', 'RUN_INTEGRATION']
		);
	});

	test('обёртка над обёрткой и параметры с Знач, аннотацией и значением по умолчанию', () => {
		assert.deepEqual(
			environmentVariablesInCode([
				module(
					'Окружение',
					'Функция Значение(&Пластилин("лог") Знач Лог, Знач Имя, Знач ПоУмолчанию = "") Экспорт',
					'	Возврат ?(ПолучитьПеременнуюСреды(Имя) = Неопределено, ПоУмолчанию, ПолучитьПеременнуюСреды(Имя));',
					'КонецФункции',
					'Функция Флаг(Имя) Экспорт',
					'	Возврат Значение(Неопределено, Имя) = "true";',
					'КонецФункции'
				),
				script('Если Окружение.Флаг("APP_DEBUG") Тогда', 'КонецЕсли;'),
			]),
			['APP_DEBUG']
		);
	});

	test('метод, который меняет параметр, вызовы методов объектов и чужих файлов обёртками не считаются', () => {
		assert.deepEqual(
			environmentVariablesInCode([
				module(
					'Окружение',
					'Функция СПрефиксом(Имя) Экспорт',
					'	Имя = "APP_" + Имя;',
					'	Возврат ПолучитьПеременнуюСреды(Имя);',
					'КонецФункции',
					'Функция Значение(Имя) Экспорт',
					'	Возврат ПолучитьПеременнуюСреды(Имя);',
					'КонецФункции'
				),
				script(
					'А = Окружение.СПрефиксом("CHANGED");',
					'Б = Настройки.Окружение.Значение("NESTED");',
					'В = Объект().Значение("FROM_OBJECT");',
					'Г = Значение("NOT_LOCAL");'
				),
			]),
			[]
		);
	});

	test('привязки опций cli: аннотация autumn-cli и текучий метод, несколько имён через пробел', () => {
		assert.deepEqual(
			environmentVariablesInCode([
				script(
					'&Опция(Имя = "ibconnection", Описание = "Строка подключения")',
					'&ВОкружении("VRUNNER_IBCONNECTION")',
					'Перем СтрокаПодключения Экспорт;',
					'&ВОкружении(Значение = "GITHUB_TOKEN GH_TOKEN")',
					'Перем Токен Экспорт;',
					'Процедура ОписаниеКоманды(Команда) Экспорт',
					'	Команда.Опция("u user", "", "Пользователь").ВОкружении("APP_USER APP_LOGIN");',
					'КонецПроцедуры'
				),
			]),
			['APP_LOGIN', 'APP_USER', 'GH_TOKEN', 'GITHUB_TOKEN', 'VRUNNER_IBCONNECTION']
		);
	});

	test('обёртка над текучим методом привязки', () => {
		assert.deepEqual(
			environmentVariablesInCode([
				script(
					'Процедура ДобавитьОпцию(Команда, Имя, Переменная)',
					'	Команда.Опция(Имя, "", "").ВОкружении(Переменная);',
					'КонецПроцедуры',
					'ДобавитьОпцию(Команда, "token", "APP_TOKEN APP_KEY");'
				),
			]),
			['APP_KEY', 'APP_TOKEN']
		);
	});

	test('свой метод с именем встроенной функции её перекрывает', () => {
		assert.deepEqual(
			environmentVariablesInCode([
				script(
					'Функция ПолучитьПеременнуюСреды(Ключ)',
					'	Возврат Настройки[Ключ];',
					'КонецФункции',
					'А = ПолучитьПеременнуюСреды("SHADOWED");'
				),
			]),
			[]
		);
	});
});
